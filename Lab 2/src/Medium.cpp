#include <iostream>
#include <windows.h>

int main()
{
    // Устанавливаем UTF-8, чтобы русский текст корректно
    // отображался в терминале Windows.
    SetConsoleOutputCP(CP_UTF8);
    SetConsoleCP(CP_UTF8);

    // Общее количество секунд, введённое пользователем.
    unsigned long long totalSeconds = 0;

    // Переменные для хранения результата преобразования.
    unsigned long long hours = 0;
    unsigned long long minutes = 0;
    unsigned long long seconds = 0;

    // Повторяем ввод, пока пользователь не введёт
    // корректное положительное целое число.
    while (true)
    {
        std::cout << "Введите количество секунд от 1 до 4.000.000.000: ";
        std::cin >> totalSeconds;

        // Проверяем, удалось ли считать число.
        // Ошибка возникает, например, при вводе текста вместо числа.
        if (std::cin.fail())
       {
           std::cout << "Ошибка: необходимо ввести целое число!\n";

           // Сбрасываем состояние ошибки потока ввода.
           std::cin.clear();

           // Удаляем ошибочные символы из буфера ввода
           // до конца текущей строки.
           std::cin.ignore(10000, '\n');
           // Проверяем, что число не равно нулю и не отрицательное.
       }
        else if (totalSeconds > 4000000000)
        {
            std::cout << "Ошибка: количество секунд должно быть в диапазоне от 1 до 4.000.000.000!\n";
        }
        else if (totalSeconds <= 0)
        {
            std::cout
                << "Ошибка: количество секунд должно быть больше нуля!\n";
        }
        else
        {
            // Введено корректное значение — выходим из цикла.
            break;
        }
    }

    // Находим количество полных часов.
    // При целочисленном делении дробная часть отбрасывается.
    hours = totalSeconds / 3600;

    // Находим секунды, оставшиеся после выделения часов.
    // Оператор % возвращает остаток от целочисленного деления.
    int remainingSeconds = totalSeconds % 3600;

    // Находим количество полных минут.
    minutes = remainingSeconds / 60;

    // Находим оставшиеся секунды.
    seconds = remainingSeconds % 60;

    // Выводим результат преобразования.
    std::cout << "\nРезультат:\n";
    std::cout << "Часы: " << hours << '\n';
    std::cout << "Минуты: " << minutes << '\n';
    std::cout << "Секунды: " << seconds << '\n';

    return 0;
}